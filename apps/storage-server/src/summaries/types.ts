/**
 * Book summaries: the shapes the steps pass along (session 2, the engine session 3 builds on).
 */

/** What an extracted item records. */
export type ItemKind = 'event' | 'character' | 'relationship' | 'reveal' | 'term' | 'thread';
export const ITEM_KINDS: ItemKind[] = [
  'event',
  'character',
  'relationship',
  'reveal',
  'term',
  'thread',
];

/** One item a model extracted, after the quote check (position = where its quote is). */
export interface CheckedItem {
  /** "<model short>:<chapter>:<n>", stable for the same answer. */
  id: string;
  model: string;
  chapter: number;
  kind: ItemKind;
  text: string;
  quote: string;
  names: string[];
  position: number;
}

/** Why items were left out, counted per step (shown on the judging page). */
export interface DropCounts {
  /** Extracted items whose quote isn't in this book. */
  quoteNotFound: number;
  /** Items only one model found that the other model's check didn't support. */
  notSupported: number;
  /** Written items that cited nothing that exists, or a name not in the book. */
  writtenDropped: number;
}

/** A written summary item: what the app shows. */
export interface SummaryItem {
  /** Stable reference inside the summary ("ch3.2", "char.0", ...). */
  ref: string;
  text: string;
  /** Characters and Terms: the bold heading (a name or a term). */
  heading?: string;
  /** Relationships: the two people. */
  between?: [string, string];
  /** The checked items it rests on. */
  cites: string[];
  /** The evidence quote (from a cited item) and where it is; shown only when `showQuote`. */
  quote: string | null;
  position: number | null;
  showQuote: boolean;
}

export interface SummarySection {
  key: 'overview' | 'chapters' | 'characters' | 'relationships' | 'terms' | 'threads';
  /** Chapter by chapter: one group per chapter. */
  groups: { chapter?: number; title?: string; items: SummaryItem[] }[];
}

export interface Summary {
  lang: string;
  bookTitle: string;
  /** "generated by <model> on <date>". */
  models: string[];
  madeAt: number;
  sections: SummarySection[];
  /** Characters only mentioned (one "Also mentioned" line). */
  alsoMentioned: string[];
}
